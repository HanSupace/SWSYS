"""Generate portable PostgreSQL SQL from the reviewed PSV dataset (no DB access)."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

def rows(name):
    return [s.split('|') for s in (HERE / name).read_text(encoding='utf-8').splitlines()
            if s.strip() and not s.startswith('#')]

def quote(value):
    return "'" + value.replace("'", "''") + "'"

catalog = (ROOT / 'src/main/java/com/daily/lastsys/features/emotion/EmotionCatalog.java').read_text(encoding='utf-8')
emotions = dict(re.findall(r'new EmotionMeta\("[^"]+", "[^"]+", "[^"]+", "([^"]+)", "[^"]+", "(#[A-Fa-f0-9]+)"', catalog))
places = {r[0]: r[1:] for r in rows('seunghak-places.psv')}
records = rows('seunghak-records.psv')
assert len(records) == 100 and len({r[2] for r in records}) == 100
assert {r[1] for r in records} == set(emotions)
assert all(len(r) == 5 and len(r[2]) <= 24 and len(r[3]) <= 2000 for r in records)
names = ['책갈피산책', '느린점심', '초록공책', '오후한페이지', '언덕의바람', '작은쉼표', '구름발걸음', '커피와여백', '나무사이빛', '오늘의창가']
user_values = ',\n'.join('(' + quote(f'seed_seunghak_v1_{i+1:02d}') + ',' + quote(n) + ')' for i,n in enumerate(names))
values = []
for i, (place, emotion, title, body, tags) in enumerate(records):
    location, lat, lng = places[place]
    owner = f'seed_seunghak_v1_{(i+i//10)%10+1:02d}'
    values.append('(' + ','.join([str(i+1), quote(owner), lat, lng, quote(emotion), quote(emotions[emotion]), quote(title), quote(location), quote(body), 'ARRAY[' + ','.join(quote(t) for t in tags.split(',')) + ']::text[]']) + ')')

sql = """-- Generated by scripts/seed/generate_sql.py. UTF-8. No credentials.
-- Apply to an initialized project database. Existing rows are never updated/deleted.
-- Same dataset as SeedSeunghak.java: adopts the earlier 100 rows without duplication.
-- Approximate POI coordinates; not surveyed building entrances.
BEGIN;
SET LOCAL lock_timeout = '15s';
SET LOCAL statement_timeout = '120s';
SELECT pg_advisory_xact_lock(65261003100);
LOCK TABLE users, emotion_map_markers, emotion_map_marker_tags IN SHARE ROW EXCLUSIVE MODE;

DO $guard$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='emotion_map_markers'::regclass
      AND confrelid='users'::regclass AND contype='f'
      AND conkey=ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid='emotion_map_markers'::regclass AND attname='user_id')]::smallint[]
      AND confkey=ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid='users'::regclass AND attname='id')]::smallint[]) THEN
    RAISE EXCEPTION 'Expected emotion_map_markers.user_id -> users.id foreign key';
  END IF;
END $guard$;

CREATE TEMP TABLE _seed_users(username text PRIMARY KEY, nickname text NOT NULL) ON COMMIT DROP;
INSERT INTO _seed_users VALUES
""" + user_values + ";\n" + """
CREATE TEMP TABLE _seed_expected(
  n integer PRIMARY KEY, username text NOT NULL, latitude numeric(10,7), longitude numeric(10,7),
  emotion_label text, emotion_color text, title text UNIQUE, location_name text, description text, tags text[]
) ON COMMIT DROP;
INSERT INTO _seed_expected VALUES
""" + ',\n'.join(values) + ";\n" + """
DO $validate$
BEGIN
  IF (SELECT count(*) FROM _seed_expected) <> 100
    OR (SELECT count(DISTINCT emotion_label) FROM _seed_expected) <> 8
    OR EXISTS (SELECT 1 FROM _seed_expected WHERE length(title)>24 OR length(location_name)>80 OR length(description)>2000
       OR latitude NOT BETWEEN 35.10 AND 35.13 OR longitude NOT BETWEEN 128.95 AND 128.99) THEN
    RAISE EXCEPTION 'Invalid seed dataset';
  END IF;
  IF EXISTS (SELECT 1 FROM _seed_expected e CROSS JOIN LATERAL unnest(e.tags) t(code)
      LEFT JOIN recommendation_tag_catalog c ON c.tag_code=t.code WHERE c.tag_code IS NULL) THEN
    RAISE EXCEPTION 'Missing existing recommendation tags; initialize project schema first';
  END IF;
  IF EXISTS (SELECT 1 FROM emotion_map_markers m JOIN _seed_expected e ON e.emotion_label=m.emotion_label
      WHERE m.emotion_color<>e.emotion_color) THEN
    RAISE EXCEPTION 'Existing emotion colors differ from project EmotionCatalog';
  END IF;
  IF EXISTS (SELECT 1 FROM users u JOIN _seed_users s USING(username)
      WHERE u.nickname<>s.nickname OR u.password_hash NOT LIKE '!disabled-%') THEN
    RAISE EXCEPTION 'Test username collides with an existing non-test account; no data changed';
  END IF;
END $validate$;

-- Full row snapshots prove that all existing users, records and tag links survive unchanged.
CREATE TEMP TABLE _seed_before_users ON COMMIT DROP AS SELECT id,to_jsonb(u) AS data FROM users u;
CREATE TEMP TABLE _seed_before_records ON COMMIT DROP AS SELECT id,to_jsonb(m) AS data FROM emotion_map_markers m;
CREATE TEMP TABLE _seed_before_tags ON COMMIT DROP AS SELECT marker_id,tag_code FROM emotion_map_marker_tags;
CREATE TEMP TABLE _seed_new_users(id bigint) ON COMMIT DROP;
CREATE TEMP TABLE _seed_new_records(id bigint) ON COMMIT DROP;

WITH inserted AS (
 INSERT INTO users(username,password_hash,nickname)
 SELECT s.username,'!disabled-' || md5(s.username || clock_timestamp()::text || random()::text),s.nickname
 FROM _seed_users s WHERE NOT EXISTS (SELECT 1 FROM users u WHERE u.username=s.username)
 RETURNING id
) INSERT INTO _seed_new_users SELECT id FROM inserted;

WITH inserted AS (
 INSERT INTO emotion_map_markers(user_id,latitude,longitude,emotion_label,emotion_color,title,location_name,description,tags_classified,created_at,updated_at)
 SELECT u.id,e.latitude,e.longitude,e.emotion_label,e.emotion_color,e.title,e.location_name,e.description,true,
   (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul') - (101-e.n)*interval '71 minutes',
   (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul') - (101-e.n)*interval '71 minutes'
 FROM _seed_expected e JOIN users u USING(username)
 WHERE NOT EXISTS (SELECT 1 FROM emotion_map_markers m WHERE m.user_id=u.id AND m.title=e.title)
 ORDER BY e.n RETURNING id
) INSERT INTO _seed_new_records SELECT id FROM inserted;

-- Only NEW records receive tags; existing links are not altered, even if inconsistent.
INSERT INTO emotion_map_marker_tags(marker_id,tag_code)
SELECT m.id,t.code FROM _seed_new_records n JOIN emotion_map_markers m ON m.id=n.id
 JOIN users u ON u.id=m.user_id JOIN _seed_expected e ON e.username=u.username AND e.title=m.title
 CROSS JOIN LATERAL unnest(e.tags) t(code);

DO $verify$
BEGIN
  IF (SELECT count(*) FROM emotion_map_markers m JOIN users u ON u.id=m.user_id JOIN _seed_users s USING(username)) <> 100 THEN
    RAISE EXCEPTION 'Expected exactly 100 records for this seed batch';
  END IF;
  IF EXISTS (
    SELECT 1 FROM _seed_expected e JOIN users u USING(username)
    LEFT JOIN emotion_map_markers m ON m.user_id=u.id AND m.title=e.title
    WHERE m.id IS NULL OR m.emotion_label IS DISTINCT FROM e.emotion_label OR m.emotion_color IS DISTINCT FROM e.emotion_color
      OR m.latitude IS DISTINCT FROM e.latitude OR m.longitude IS DISTINCT FROM e.longitude
      OR m.location_name IS DISTINCT FROM e.location_name OR m.description IS DISTINCT FROM e.description OR m.tags_classified IS DISTINCT FROM true
      OR (SELECT array_agg(t.tag_code::text ORDER BY t.tag_code) FROM emotion_map_marker_tags t WHERE t.marker_id=m.id)
          IS DISTINCT FROM (SELECT array_agg(code ORDER BY code) FROM unnest(e.tags) code)
  ) THEN RAISE EXCEPTION 'Existing seed differs from expected dataset; rolled back without modifying existing data'; END IF;
  IF EXISTS (SELECT 1 FROM _seed_before_users b LEFT JOIN users u USING(id) WHERE b.data IS DISTINCT FROM to_jsonb(u))
    OR EXISTS (SELECT 1 FROM _seed_before_records b LEFT JOIN emotion_map_markers m USING(id) WHERE b.data IS DISTINCT FROM to_jsonb(m))
    OR EXISTS (SELECT * FROM _seed_before_tags EXCEPT SELECT marker_id,tag_code FROM emotion_map_marker_tags) THEN
    RAISE EXCEPTION 'Existing data preservation check failed';
  END IF;
END $verify$;

SELECT (SELECT count(*) FROM _seed_new_users) AS inserted_users,
       (SELECT count(*) FROM _seed_new_records) AS inserted_records,
       100 AS verified_seed_records, true AS existing_rows_preserved;
SELECT m.emotion_label,count(*) AS records FROM emotion_map_markers m JOIN users u ON u.id=m.user_id
 JOIN _seed_users s USING(username) GROUP BY m.emotion_label ORDER BY m.emotion_label;
SELECT m.location_name,m.latitude,m.longitude,count(*) AS records FROM emotion_map_markers m JOIN users u ON u.id=m.user_id
 JOIN _seed_users s USING(username) GROUP BY m.location_name,m.latitude,m.longitude ORDER BY m.location_name;
COMMIT;
"""
(HERE/'seunghak-100.sql').write_text(sql, encoding='utf-8')
print('Generated seunghak-100.sql: 100 records, 10 places, 8 existing emotions.')
